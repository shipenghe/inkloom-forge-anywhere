// Build the synchronous catalog used by popup, options and isolated page scripts.
// Browser-owned metadata uses _locales directly. No remote translation requests.
import { readFile, writeFile } from 'node:fs/promises'
const root = new URL('./', import.meta.url)
const load = async (locale) =>
  JSON.parse(
    await readFile(new URL(`_locales/${locale}/messages.json`, root), 'utf8')
  )
const en = await load('en'),
  zh = await load('zh_CN')
const entries = Object.entries(zh).map(([key, value]) => {
  if (!en[key]?.message) throw new Error(`Missing English translation: ${key}`)
  return [key, value.message, en[key].message]
})
if (Object.keys(en).length !== entries.length)
  throw new Error('Locale keys differ')
await writeFile(
  new URL('_locales/zh_TW/messages.json', root),
  JSON.stringify(zh, null, 2) + '\n'
)
await writeFile(
  new URL('i18n-data.js', root),
  '// Generated by buildI18n.mjs from _locales; do not edit.\n;(() => { globalThis.ForgeLocaleMessages = ' +
    JSON.stringify(entries) +
    ' })()\n'
)
